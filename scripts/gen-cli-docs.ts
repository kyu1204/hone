const SECTIONS: [string, string, () => string][] = [
  ["Everyday", "init", initUsage],
  ["Everyday", "draft", draftUsage],
  ["Everyday", "test", runUsage],
  ["Everyday", "test --ci", ciUsage],
  ["Everyday", "sharpen", sharpenUsage],
  ["Steps that `hone sharpen` runs for you", "cluster", clusterUsage],
  ["Steps that `hone sharpen` runs for you", "calibrate", calibrateUsage],
  ["Steps that `hone sharpen` runs for you", "evolve", evolveUsage],
  ["Steps that `hone sharpen` runs for you", "optimize", optimizeUsage],
  ["Steps that `hone sharpen` runs for you", "ablate", ablateUsage],
  ["Steps that `hone sharpen` runs for you", "compare", compareUsage],
  ["Steps that `hone sharpen` runs for you", "power", powerUsage],
  ["Looking at results", "tui", tuiUsage],
  ["Looking at results", "matrix", matrixUsage],
  ["Looking at results", "explain", explainUsage],
  ["Looking at results", "diff", diffUsage],
  ["Looking at results", "fork", forkUsage],
  ["Other tools", "bisect", bisectUsage],
  ["Other tools", "export", exportUsage],
  ["Other tools", "import", importUsage],
  ["Other tools", "serve", serveUsage],
  ["Other tools", "guide", guideUsage],
];

export function renderCliDocs(): string {
  const out: string[] = ["# CLI reference", "", "Generated by `bun scripts/gen-cli-docs.ts` from each command's `--help`; do not edit by hand.", "", "`hone --help` lists the everyday commands and `hone help all` the rest. Plain `hone` in a terminal opens the dashboard (`hone tui`). Every command accepts `--help`.", ""];
  let section = "";
  for (const [sec, name, usage] of SECTIONS) {
    if (sec !== section) {
      section = sec;
      out.push(`## ${sec}`, "");
    }
    out.push(`### hone ${name}`, "", "```", usage().trimEnd(), "```", "");
  }
  return `${out.join("\n").trimEnd()}\n`;
}

if (import.meta.main) {
  const file = new URL("../docs/cli.md", import.meta.url).pathname;
  await Bun.write(file, renderCliDocs());
  console.log(`wrote ${file}`);
}
