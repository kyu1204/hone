// Generates docs/cli.md from each command's usage string. `bun scripts/gen-cli-docs.ts` writes it; the test checks it is current.
import { ablateUsage } from "../src/cli/commands/ablate";
import { bisectUsage } from "../src/cli/commands/bisect";
import { calibrateUsage } from "../src/cli/commands/calibrate";
import { ciUsage } from "../src/cli/commands/ci";
import { clusterUsage } from "../src/cli/commands/cluster";
import { compareUsage } from "../src/cli/commands/compare";
import { diffUsage } from "../src/cli/commands/diff";
import { evolveUsage } from "../src/cli/commands/evolve";
import { explainUsage } from "../src/cli/commands/explain";
import { exportUsage } from "../src/cli/commands/export";
import { forkUsage } from "../src/cli/commands/fork";
import { importUsage } from "../src/cli/commands/import";
import { initUsage } from "../src/cli/commands/init";
import { matrixUsage } from "../src/cli/commands/matrix";
import { optimizeUsage } from "../src/cli/commands/optimize";
import { powerUsage } from "../src/cli/commands/power";
import { reportUsage } from "../src/cli/commands/report";
import { runUsage } from "../src/cli/commands/run";
import { serveUsage } from "../src/cli/commands/serve";
import { tuiUsage } from "../src/cli/commands/tui";

const SECTIONS: [string, string, () => string][] = [
  ["Measure", "run", runUsage],
  ["Measure", "matrix", matrixUsage],
  ["Measure", "compare", compareUsage],
  ["Measure", "ci", ciUsage],
  ["Measure", "power", powerUsage],
  ["Localize", "explain", explainUsage],
  ["Localize", "diff", diffUsage],
  ["Localize", "cluster", clusterUsage],
  ["Localize", "calibrate", calibrateUsage],
  ["Correct", "fork", forkUsage],
  ["Correct", "evolve", evolveUsage],
  ["Correct", "optimize", optimizeUsage],
  ["Correct", "ablate", ablateUsage],
  ["Correct", "bisect", bisectUsage],
  ["Share", "report", reportUsage],
  ["Share", "export", exportUsage],
  ["Share", "import", importUsage],
  ["Share", "serve", serveUsage],
  ["Setup", "init", initUsage],
  ["Setup", "tui", tuiUsage],
];

export function renderCliDocs(): string {
  const out: string[] = ["# CLI reference", "", "Generated by `bun scripts/gen-cli-docs.ts` from each command's `--help`; do not edit by hand.", "", "Plain `hone` in a terminal opens the dashboard (`hone tui`). Every command accepts `--help`.", ""];
  let section = "";
  for (const [sec, name, usage] of SECTIONS) {
    if (sec !== section) {
      section = sec;
      out.push(`## ${sec}`, "");
    }
    out.push(`### hone ${name}`, "", "```", usage().trimEnd(), "```", "");
  }
  return `${out.join("\n").trimEnd()}\n`;
}

if (import.meta.main) {
  const file = new URL("../docs/cli.md", import.meta.url).pathname;
  await Bun.write(file, renderCliDocs());
  console.log(`wrote ${file}`);
}
